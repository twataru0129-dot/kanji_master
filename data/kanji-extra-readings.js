/*
 * 一文字の読み問題で、追加で正解にする読み
 * ------------------------------------------------------------
 * 漢字データ（data/kanji-*.js）の音訓から作る正解候補（例: 暮 → ぼ・く・くれる・くらす）に加えて、
 * 「その漢字1字で書かれる言葉の読み」を正解にしたいときに、ここに1行ずつ追加します。
 *
 *   { kanji: '暮', reading: 'くれ', word: '暮れ', type: 'kun' }
 *     kanji   … 対象の漢字
 *     reading … 正解にする読み（ひらがな）
 *     word    … その読みの言葉（答え合わせで「「くれ」（「暮れ」の読み）」のように表示）
 *     type    … 'kun'（訓読み）または 'on'（音読み）
 *
 * ・一文字の読み問題の判定にだけ使います。漢字図鑑やプリントの読み表示・送り仮名表記は変わりません。
 * ・文の中の読み・生活漢字・サクラモードは、それぞれの問題に登録された読みで判定します（ここは使いません）。
 * ・前方一致や活用形の自動生成はしません。正解にしたい読みだけを、1つずつはっきり書いてください。
 */
KanjiApp.KanjiDB.registerExtraReadings([
  { kanji: '暮', reading: 'くれ', word: '暮れ', type: 'kun' }, // 年の暮れ・日の暮れ
]);
